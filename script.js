function updateProgress() {

    if (
        !playerReady ||
        !isPlaying
    ) return;


    try {

        const current =
            player.getCurrentTime();


        const duration =
            player.getDuration();


        if (
            !duration ||
            duration <= 0
        ) return;


        const percentage =
            (
                current /
                duration
            ) * 100;


        progress.style.width =
            percentage + "%";


        currentTimeElement.textContent =
            formatTime(current);


        totalTimeElement.textContent =
            formatTime(duration);

    }

    catch (error) {}

}


