const backgroundChangeBtn =
    document.getElementById(
        "backgroundChangeBtn"
    );


backgroundChangeBtn.addEventListener(
    "click",
    function () {

        backgroundIndex++;


        if (
            backgroundIndex >=
            backgrounds.length
        ) {

            backgroundIndex = 0;

        }


        const nextImage =
            new Image();


        nextImage.src =
            backgrounds[backgroundIndex];


        nextImage.onload =
            function () {

                /*
                   New image goes into
                   the invisible layer
                */

                bg2.style.backgroundImage =
                    `url("${backgrounds[backgroundIndex]}")`;


                /*
                   Fade new image IN
                */

                bg2.style.opacity = "1";


                /*
                   Old image stays underneath
                */

                setTimeout(
                    function () {

                        bg1.style.backgroundImage =
                            bg2.style.backgroundImage;


                        bg1.style.opacity = "1";

                        bg2.style.opacity = "0";

                    },
                    1500
                );

            };

    }
);
