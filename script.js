/* =========================================================
   PLAYER STATE
========================================================= */

function onPlayerStateChange(event) {


    if (
        event.data ===
        YT.PlayerState.PLAYING
    ) {

        isPlaying = true;

        updatePlayButton();

        startProgressTimer();

        updateTrackFromPlayer();

    }


    else if (
        event.data ===
        YT.PlayerState.PAUSED
    ) {

        isPlaying = false;

        updatePlayButton();

    }


    else if (
        event.data ===
        YT.PlayerState.ENDED
    ) {

        isPlaying = false;

        updatePlayButton();

        setTimeout(
            updateTrackFromPlayer,
            500
        );

    }

}


