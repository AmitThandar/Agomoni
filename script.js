/* =========================================================
   REAL-TIME DURGA PUJA COUNTDOWN
   Target: 16 October 2026
========================================================= */

const pujaDate = new Date(
    2026,
    9,      // October
    16,
    0,      // 00 hours
    0,      // 00 minutes
    0       // 00 seconds
).getTime();


function updateCountdown() {

    const now = Date.now();

    const difference =
        pujaDate - now;


    /* Puja date reached */

    if (difference <= 0) {

        countdownText.textContent =
            "Durga Pujo has arrived";

        if (heroCountdown) {

            heroCountdown.textContent =
                "শুভ শারদীয়া";

        }

        return;

    }


    /* Calculate */

    const days =
        Math.floor(
            difference /
            (1000 * 60 * 60 * 24)
        );


    const hours =
        Math.floor(
            (difference %
                (1000 * 60 * 60 * 24))
            /
            (1000 * 60 * 60)
        );


    const minutes =
        Math.floor(
            (difference %
                (1000 * 60 * 60))
            /
            (1000 * 60)
        );


    const seconds =
        Math.floor(
            (difference %
                (1000 * 60))
            /
            1000
        );


    /* Top countdown */

    countdownText.textContent =
        `${days}d ` +
        `${String(hours).padStart(2, "0")}h ` +
        `${String(minutes).padStart(2, "0")}m ` +
        `${String(seconds).padStart(2, "0")}s`;


    /* Hero countdown */

    if (heroCountdown) {

        heroCountdown.textContent =
            `${days} days until Durga Pujo`;

    }

}


/* Start immediately */

updateCountdown();


/* Update every second */

setInterval(
    updateCountdown,
    1000
);


