function onYouTubeIframeAPIReady() {

    console.log(
        "YouTube API ready"
    );


    player =
        new YT.Player(
            "youtube-player",
            {

                height: "1",

                width: "1",

                playerVars: {

                    autoplay: 0,

                    controls: 0,

                    disablekb: 1,

                    playsinline: 1,

                    rel: 0,

                    modestbranding: 1

                },

                events: {

                    onReady:
                        onPlayerReady,

                    onStateChange:
                        onPlayerStateChange,

                    onError:
                        onPlayerError

                }

            }
        );

}


/* =========================================================
   PLAYER READY
========================================================= */

function onPlayerReady() {

    playerReady = true;

    player.setVolume(volume);


    /*
       Initial UI
    */

    playlistName.textContent =
        playlists.durga.name;

    playlistDescription.textContent =
        playlists.durga.description;


    renderTracks("durga");


    /*
       Initial album image
    */

    albumImage.src =
        createAlbumIcon();

}


/* =========================================================
   LOAD PLAYLIST
========================================================= */

function loadPlaylist(
    key,
    index = 0,
    autoplay = false
) {

    const playlist =
        playlists[key];


    if (!playlist) return;


    if (
        !playlist.id ||
        playlist.id ===
        "YOUR_MAHALAYA_PLAYLIST_ID"
    ) {

        showToast(
            "Mahalaya playlist ID এখনো বসানো হয়নি"
        );

        return;

    }


    if (!playerReady) {

        showToast(
            "Music player loading..."
        );

        return;

    }


    currentPlaylist = key;

    currentIndex = index;

    playlistLoaded = true;


    playlistName.textContent =
        playlist.name;

    playlistDescription.textContent =
        playlist.description;


    renderTracks(key);


    /*
       Load YouTube playlist
    */

    player.loadPlaylist({

        listType: "playlist",

        list: playlist.id,

        index: index

    });


    player.setVolume(volume);


    if (autoplay) {

        setTimeout(
            () => {

                player.playVideo();

            },
            800
        );

    }

}


